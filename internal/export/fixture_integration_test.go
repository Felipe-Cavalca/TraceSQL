var itBooleanos = itTabela{"booleanos", []itCol{colID(), colCod(), {nome: "lote_id", tipo: tID, fk: "tipos_lote.id"}, {nome: "c_bool", tipo: tp("boolean", "tinyint(1)", "BOOLEAN")}}}

func itSetupBooleanos(t *testing.T, b *itBanco) {
	t.Helper()
	itCriaTabelas(t, b, itTiposLote, itBooleanos)
	itInsere(t, b, itTiposLote, itLinha{"id": 1, "codigo": "lote-1"})
	itInsere(t, b, itBooleanos,
		itLinha{"id": 1, "codigo": "b-verdadeiro", "lote_id": 1, "c_bool": true},
		itLinha{"id": 2, "codigo": "b-falso", "lote_id": 1, "c_bool": false},
		itLinha{"id": 3, "codigo": "b-nulo", "lote_id": 1})
}
