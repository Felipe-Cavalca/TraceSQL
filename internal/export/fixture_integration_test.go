// itCol descreve uma coluna da fixture com o tipo nativo de cada motor.
type itCol struct {
	nome    string
	tipo    [3]string // postgres, mysql, sqlite
	pk      bool
	naoNulo bool
	auto    bool   // identidade / AUTO_INCREMENT / AUTOINCREMENT
	fk      string // "tabela.coluna" referenciada
	livre   bool   // tipo muda legitimamente: só presença e dados são conferidos
	cast    string // cast do Postgres para o parâmetro (dec, json, data...)
}

type itTabela struct {
	nome string
	cols []itCol
}

type itLinha = map[string]any

func tp(pg, my, sl string) [3]string { return [3]string{pg, my, sl} }

var (
	tID    = tp("bigint", "bigint", "INTEGER")
	tCod   = tp("varchar(20)", "varchar(20)", "VARCHAR(20)")
	tNome  = tp("varchar(40)", "varchar(40)", "VARCHAR(40)")
	tInt   = tp("integer", "int", "INTEGER")
	tTexto = tp("text", "text", "TEXT")
)

func colID() itCol  { return itCol{nome: "id", tipo: tID, pk: true} }
func colCod() itCol { return itCol{nome: "codigo", tipo: tCod, naoNulo: true} }

// itCriaTabelas cria as tabelas no motor do banco. No SQLite as chaves
// estrangeiras vão inline; no Postgres e no MySQL entram por ALTER TABLE depois
// de todas as tabelas existirem (permite ciclos).
func itCriaTabelas(t *testing.T, b *itBanco, tabelas ...itTabela) {
	t.Helper()
	i := b.motor.idx()
	for _, tab := range tabelas {
		var partes []string
		for _, c := range tab.cols {
			p := itQuote(b.motor, c.nome) + " " + c.tipo[i]
			switch {
			case c.auto && i == 2:
				p = itQuote(b.motor, c.nome) + " INTEGER PRIMARY KEY AUTOINCREMENT"
			case c.auto && i == 0:
				p += " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
			case c.auto && i == 1:
				p += " AUTO_INCREMENT PRIMARY KEY"
			case c.pk:
				p += " PRIMARY KEY"
			}
			if c.naoNulo {
				p += " NOT NULL"
			}
			partes = append(partes, p)
		}
		if i == 2 {
			for _, c := range tab.cols {
				if ref, col, ok := strings.Cut(c.fk, "."); ok {
					partes = append(partes, "FOREIGN KEY ("+itQuote(b.motor, c.nome)+") REFERENCES "+itQuote(b.motor, ref)+" ("+itQuote(b.motor, col)+")")
				}
			}
		}
		b.exec(t, "CREATE TABLE "+itQuote(b.motor, tab.nome)+" ("+strings.Join(partes, ", ")+")")
	}
	if i == 2 {
		return
	}
	for _, tab := range tabelas {
		for _, c := range tab.cols {
			if ref, col, ok := strings.Cut(c.fk, "."); ok {
				b.exec(t, "ALTER TABLE "+itQuote(b.motor, tab.nome)+" ADD FOREIGN KEY ("+itQuote(b.motor, c.nome)+") REFERENCES "+itQuote(b.motor, ref)+" ("+itQuote(b.motor, col)+")")
			}
		}
	}
}

var itCastPG = map[string]string{"dec": "numeric", "json": "jsonb", "data": "date", "hora": "time", "ts": "timestamp"}

// itInsere grava linhas. Colunas fora do mapa ficam NULL (ou no padrão).
func itInsere(t *testing.T, b *itBanco, tab itTabela, linhas ...itLinha) {
	t.Helper()
	for _, l := range linhas {
		var nomes, ph []string
		var args []any
		for _, c := range tab.cols {
			v, ok := l[c.nome]
			if !ok {
				continue
			}
			nomes = append(nomes, itQuote(b.motor, c.nome))
			p := "?"
			if b.motor.idx() == 0 {
				if cast, ok := itCastPG[c.cast]; ok {
					p = "CAST(CAST(? AS text) AS " + cast + ")"
				}
			}
			ph = append(ph, p)
			if bv, isBool := v.(bool); isBool && b.motor.idx() != 0 {
				if bv {
					v = 1
				} else {
					v = 0
				}
			}
			args = append(args, v)
		}
		b.exec(t, "INSERT INTO "+itQuote(b.motor, tab.nome)+" ("+strings.Join(nomes, ", ")+") VALUES ("+strings.Join(ph, ", ")+")", args...)
	}
}

